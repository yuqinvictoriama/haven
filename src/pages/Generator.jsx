import { useEffect, useRef, useState } from 'react'
import { useRoute, navigate } from '../lib/router.js'
import { db, uid } from '../lib/db.js'
import { fmtDate, download } from '../lib/media.js'
import { generate, isNoKey } from '../lib/api.js'
import { DOC_KINDS, demoDocument } from '../lib/demo.js'
import { pathsFor } from '../content/paths.js'
import { renderMarkdown } from '../lib/markdown.js'
import { useApp } from '../App.jsx'
import { LEGAL_DISCLAIMER, NEXT_STEPS } from '../content/safetyText.js'
import { Spark, Copy, Share, Download, Print, Alert, Stop, kindIcon } from '../components/Icons.jsx'

const EVERYTHING = ['advocate_summary', 'timeline', 'exhibit_list', 'dvro', 'dv101', 'criminal_case', 'safety_plan']
const titleOf = (k) => DOC_KINDS.find((d) => d.kind === k)?.title || k

export default function Generator({ kind }) {
  const { query } = useRoute()
  const { settings, setSettings, claudeMode } = useApp()
  const meta = DOC_KINDS.find((d) => d.kind === kind)
  const [items, setItems] = useState([])
  const [selected, setSelected] = useState(new Set())
  const [notes, setNotes] = useState('')
  const [doc, setDoc] = useState('')
  const [running, setRunning] = useState(false)
  const [mode, setMode] = useState('')
  const [err, setErr] = useState('')
  const [copied, setCopied] = useState(false)
  const [showForm, setShowForm] = useState(true)
  const abortRef = useRef(null)
  const docId = query.get('doc')
  const profile = settings.profile
  const setProfile = (k, v) => setSettings((s) => ({ ...s, profile: { ...s.profile, [k]: v } }))

  useEffect(() => {
    if (!meta) navigate('/generate', { replace: true })
  }, [meta])

  useEffect(() => {
    db.all().then((all) => {
      setItems(all)
      setSelected(new Set(all.map((i) => i.id)))
    })
    if (docId) {
      db.getDoc(docId).then((d) => {
        if (d) {
          setDoc(d.markdown)
          setMode(d.mode)
          setShowForm(false)
        }
      })
    }
    return () => abortRef.current?.abort()
  }, [docId])

  const toggle = (id) => setSelected((s) => { const n = new Set(s); if (n.has(id)) n.delete(id); else n.add(id); return n })

  const simulate = (md, signal, prefix = '') =>
    new Promise((resolve) => {
      let i = 0
      const step = () => {
        if (signal?.aborted) return resolve(prefix + md.slice(0, i))
        i = Math.min(md.length, i + 60)
        setDoc(prefix + md.slice(0, i))
        if (i < md.length) setTimeout(step, 14)
        else resolve(prefix + md)
      }
      step()
    })

  const run = async () => {
    const chosen = items.filter((i) => selected.has(i.id))
    const evidence = chosen.map((e) => ({ id: e.id, kind: e.kind, title: e.title, capturedAt: e.capturedAt, notes: e.notes, text: e.text ? e.text.slice(0, 20000) : undefined, analysis: e.analysis || null }))
    const base = { jurisdiction: settings.jurisdiction || 'California', profile, evidence, notes }
    const ctrl = new AbortController()
    abortRef.current = ctrl
    setRunning(true)
    setErr('')
    setDoc('')
    setShowForm(false)
    setMode('')
    let full = ''
    let usedMode = 'live'
    try {
      if (kind === 'everything') {
        full = `# Haven packet${profile.name ? ' — ' + profile.name : ''}\n\n_Draft generated by Haven for review with an advocate or attorney. Not legal advice._\n\n## Contents\n${EVERYTHING.map((p, i) => `${i + 1}. ${titleOf(p)}`).join('\n')}\n\n---\n\n`
        setDoc(full)
        for (const part of EVERYTHING) {
          if (ctrl.signal.aborted) break
          const prefix = full
          try {
            const text = await generate({ ...base, kind: part }, (partial) => setDoc(prefix + partial), ctrl.signal)
            full = prefix + text + '\n\n---\n\n'
          } catch (e) {
            if (isNoKey(e)) {
              usedMode = 'demo'
              const md = demoDocument(part, { evidence: chosen, profile, jurisdiction: base.jurisdiction, notes })
              full = (await simulate(md, ctrl.signal, prefix)) + '\n\n---\n\n'
            } else throw e
          }
          setDoc(full)
        }
      } else {
        try {
          full = await generate({ ...base, kind }, setDoc, ctrl.signal)
        } catch (e) {
          if (isNoKey(e)) {
            usedMode = 'demo'
            full = await simulate(demoDocument(kind, { evidence: chosen, profile, jurisdiction: base.jurisdiction, notes }), ctrl.signal)
          } else throw e
        }
      }
      setMode(usedMode)
      if (full.trim() && !ctrl.signal.aborted) {
        await db.putDoc({ id: uid(), kind, title: `${meta.title}${profile.name ? ' — ' + profile.name : ''}`, createdAt: new Date().toISOString(), markdown: full, mode: usedMode })
      }
    } catch (e) {
      if (e?.name !== 'AbortError') setErr(e?.message || String(e))
    } finally {
      setRunning(false)
    }
  }

  const stop = () => abortRef.current?.abort()
  const copy = async () => {
    try { await navigator.clipboard.writeText(doc); setCopied(true); setTimeout(() => setCopied(false), 1500) } catch { /* clipboard blocked */ }
  }
  const share = async () => {
    try {
      if (navigator.share) await navigator.share({ title: meta.title, text: doc })
      else copy()
    } catch { /* cancelled */ }
  }
  const save = () => download(`${meta.title.replace(/[^\w]+/g, '_')}_${new Date().toISOString().slice(0, 10)}.md`, new Blob([doc], { type: 'text/markdown' }))

  if (!meta) return null
  return (
    <>
      {showForm && (
        <>
          <div className="card stack">
            <div>
              <h2>{meta.title}</h2>
              <p className="muted small" style={{ marginTop: 4 }}>{meta.desc}</p>
              {pathsFor(kind).length > 0 && (
                <div className="chips" style={{ marginTop: 8 }}>
                  {pathsFor(kind).map((p) => <span key={p.id} className="badge purple">{p.title} path · step {p.step}</span>)}
                </div>
              )}
              {meta.detail && <p className="small" style={{ marginTop: 8 }}>{meta.detail}</p>}
            </div>
            <div className="grid-2">
              <div className="field"><label>Your name</label><input className="input" value={profile.name} onChange={(e) => setProfile('name', e.target.value)} placeholder="As it should appear" /></div>
              <div className="field"><label>Person causing harm</label><input className="input" value={profile.respondent} onChange={(e) => setProfile('respondent', e.target.value)} placeholder="Name" /></div>
              <div className="field"><label>Relationship</label><input className="input" value={profile.relationship} onChange={(e) => setProfile('relationship', e.target.value)} placeholder="spouse, ex-partner, parent of my child" /></div>
              <div className="field"><label>Children (names, ages)</label><input className="input" value={profile.children} onChange={(e) => setProfile('children', e.target.value)} placeholder="optional" /></div>
            </div>
            <div className="field"><label>Jurisdiction</label><input className="input" value={settings.jurisdiction} onChange={(e) => setSettings({ jurisdiction: e.target.value })} placeholder="California" /></div>
            <div className="field"><label>Anything Claude should know</label><textarea className="textarea" style={{ minHeight: 70 }} value={notes} onChange={(e) => setNotes(e.target.value)} placeholder="e.g. We separated in February. I want a move-out order. Police were called once in March." /></div>
          </div>
          <div className="card">
            <div className="card-head"><h3>Evidence to include</h3><span className="tiny">{selected.size} of {items.length}</span></div>
            {items.length === 0 ? (
              <p className="muted small">No evidence yet. The draft will be a template with placeholders.</p>
            ) : (
              <div>
                <div className="row" style={{ marginBottom: 4 }}>
                  <button className="btn btn-ghost btn-sm" onClick={() => setSelected(new Set(items.map((i) => i.id)))}>Select all</button>
                  <button className="btn btn-ghost btn-sm" onClick={() => setSelected(new Set())}>None</button>
                </div>
                {items.map((it) => (
                  <label key={it.id} className="check">
                    <input type="checkbox" checked={selected.has(it.id)} onChange={() => toggle(it.id)} />
                    <span className="grow">
                      <span className="row" style={{ gap: 6 }}><span style={{ width: 16, height: 16, display: 'inline-flex' }}>{kindIcon(it.kind)}</span><span style={{ fontWeight: 600 }}>{it.title || '(untitled)'}</span></span>
                      <span className="tiny">{fmtDate(it.capturedAt)}{it.analysis ? ` · ${it.analysis.incidents?.length || 0} incidents` : ''}{it.text ? ' · text' : ''}</span>
                    </span>
                  </label>
                ))}
              </div>
            )}
          </div>
          <button className="btn btn-primary btn-lg btn-block" onClick={run} disabled={running}><Spark /> Generate {kind === 'everything' ? 'the complete packet' : 'with Claude'}</button>
          {claudeMode === 'demo' && <div className="tiny" style={{ textAlign: 'center' }}>Demo mode: a template is filled from your evidence. Add a key in More → Claude for a real draft.</div>}
          {kind === 'everything' && claudeMode !== 'demo' && <div className="tiny" style={{ textAlign: 'center' }}>Generates seven documents one after another. Takes a couple of minutes.</div>}
        </>
      )}

      {!showForm && (
        <div className="row between no-print">
          <button className="btn btn-outline btn-sm" onClick={() => { stop(); setShowForm(true) }}>{running ? 'Cancel' : 'Options / regenerate'}</button>
          <span className="tiny">{running ? 'Generating…' : mode === 'demo' ? 'Demo template' : mode === 'live' ? 'Drafted by Claude' : ''}</span>
        </div>
      )}
      {err && <div className="notice danger"><Alert />{err}</div>}
      {mode === 'demo' && !running && <div className="notice warn no-print"><Alert />This is a demo template filled from your evidence. Connect Claude for a real draft.</div>}
      {(doc || running) && (
        <>
          <div className="doc">
            <div dangerouslySetInnerHTML={{ __html: renderMarkdown(doc) }} />
            {running && <span className="cursor" />}
          </div>
          {!running && doc && (
            <div className="card card-tight">
              <div style={{ fontWeight: 650 }}>{NEXT_STEPS.title}</div>
              <ul className="small" style={{ margin: '6px 0 6px', paddingLeft: 20 }}>{NEXT_STEPS.items.map((t, i) => <li key={i}>{t}</li>)}</ul>
              <div className="tiny">{LEGAL_DISCLAIMER}</div>
            </div>
          )}
          <div className="btn-row no-print">
            {running ? (
              <button className="btn btn-danger" onClick={stop}><Stop /> Stop</button>
            ) : (
              <>
                <button className="btn btn-outline" onClick={copy}><Copy /> {copied ? 'Copied' : 'Copy'}</button>
                <button className="btn btn-outline" onClick={share}><Share /> Share</button>
                <button className="btn btn-outline" onClick={save}><Download /> .md</button>
                <button className="btn btn-outline" onClick={() => window.print()}><Print /> PDF</button>
              </>
            )}
          </div>
        </>
      )}
    </>
  )
}
